import type { Asset, AssetContainer, Coverage, SectionCoverage, SectionName } from '~/types'

type SectionOverride = Partial<Record<SectionName, Omit<SectionCoverage, 'section'>>>

const HOST_SECTIONS: SectionName[] = ['host', 'packages', 'artifacts', 'processes', 'containers']
