// zent is one entry of a test archive.
type zent struct {
	name   string
	data   []byte
	stored bool
}

func buildZip(t testing.TB, entries ...zent) []byte {
	t.Helper()
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, e := range entries {
		h := &zip.FileHeader{Name: e.name, Method: zip.Deflate}
		if e.stored {
			h.Method = zip.Store
		}
		w, err := zw.CreateHeader(h)
		if err != nil {
			t.Fatal(err)
		}
		w.Write(e.data)
	}
	if err := zw.Close(); err != nil {
		t.Fatal(err)
	}
	return buf.Bytes()
}

func pomEntry(g, a, v string) zent {
	return zent{
		name: "META-INF/maven/" + g + "/" + a + "/pom.properties",
		data: []byte("#Generated by Maven\n#Tue Jan 01 00:00:00 UTC 2024\ngroupId=" + g + "\nartifactId=" + a + "\nversion=" + v + "\n"),
	}
}

func manifestEntry(lines ...string) zent {
	return zent{name: "META-INF/MANIFEST.MF", data: []byte("Manifest-Version: 1.0\r\n" + strings.Join(lines, "\r\n") + "\r\n\r\nName: x\r\nImplementation-Version: 9\r\n")}
}

func scanBytes(b []byte, name string, lim archiveLimits) jarResult {
	return scanJar(context.Background(), bytes.NewReader(b), int64(len(b)), name, lim)
}

func sha1hex(b []byte) string {
	s := sha1.Sum(b)
	return hex.EncodeToString(s[:])
}

func TestJarPom(t *testing.T) {
	b := buildZip(t, manifestEntry("Implementation-Title: other", "Implementation-Version: 0"), pomEntry("org.example", "foo", "1.2.3"))
	res := scanBytes(b, "foo-1.2.3.jar", defaultArchiveLimits)
	if len(res.Artifacts) != 1 || len(res.Limits) != 0 || res.Corrupt != 0 {
		t.Fatalf("result = %+v", res)
	}
	a := res.Artifacts[0]
	if a.Name != "foo" || a.GroupID != "org.example" || a.ArtifactID != "foo" || a.Version != "1.2.3" ||
		a.Method != report.MethodManifest || a.PURL != "pkg:maven/org.example/foo@1.2.3" || a.Nested != nil {
		t.Fatalf("artifact = %+v", a)
	}
}

func TestJarManifest(t *testing.T) {
	cases := []struct {
		lines         []string
		name, version string
	}{
		{[]string{"Implementation-Title: Apache Commons Lang", "Implementation-Version: 3.12.0"}, "Apache Commons Lang", "3.12.0"},
		{[]string{"Bundle-SymbolicName: org.eclipse.osgi; singleton:=true", "Bundle-Version: 3.18.0.v2022"}, "org.eclipse.osgi", "3.18.0.v2022"},
		{[]string{"Bundle-Name: Long", " Name", "Bundle-Version: 1"}, "LongName", "1"},
		{[]string{"Implementation-Version: 2.0"}, "lib", "2.0"},
	}
	for _, tc := range cases {
		res := scanBytes(buildZip(t, manifestEntry(tc.lines...)), "lib-1.0.jar", defaultArchiveLimits)
		a := res.Artifacts[0]
		if a.Name != tc.name || a.Version != tc.version || a.Method != report.MethodManifest {
			t.Errorf("%v: got %q %q %s", tc.lines, a.Name, a.Version, a.Method)
		}
	}
}

func TestJarFileName(t *testing.T) {
	cases := map[string][2]string{
		"commons-lang3-3.12.0.jar": {"commons-lang3", "3.12.0"},
		"guava-31.1-jre.jar":       {"guava", "31.1-jre"},
		"log4j-1.2-api-2.17.1.jar": {"log4j-1.2-api", "2.17.1"},
		"netty-tcnative-boringssl-static-2.0.61.Final-linux-x86_64.jar": {"netty-tcnative-boringssl-static", "2.0.61.Final-linux-x86_64"},
		"app-1.0-SNAPSHOT.war": {"app", "1.0-SNAPSHOT"},
		"servlet-api.jar":      {"servlet-api", ""},
		"ecj-4.27.jar":         {"ecj", "4.27"},
	}
	for file, want := range cases {
		res := scanBytes(buildZip(t, zent{name: "a/B.class", data: []byte{0xca, 0xfe}}), file, defaultArchiveLimits)
		a := res.Artifacts[0]
		if a.Name != want[0] || a.Version != want[1] || a.Method != report.MethodStatic {
			t.Errorf("%s: got %q %q %s", file, a.Name, a.Version, a.Method)
		}
	}
}

func TestJarNested(t *testing.T) {
	inner := buildZip(t, pomEntry("org.inner", "deep", "0.1"))
	stored := buildZip(t, pomEntry("org.lib", "a", "1.0"), zent{name: "lib/deep-0.1.jar", data: inner})
	deflated := buildZip(t, pomEntry("org.lib", "b", "2.0"))
	outer := buildZip(t,
		pomEntry("com.example", "app", "1.0.0"),
		zent{name: "BOOT-INF/lib/a-1.0.jar", data: stored, stored: true},
		zent{name: "WEB-INF/lib/b-2.0.jar", data: deflated},
		zent{name: "BOOT-INF/classes/"},
	)
	res := scanBytes(outer, "app-1.0.0.jar", defaultArchiveLimits)
	if len(res.Limits) != 0 || res.Corrupt != 0 {
		t.Fatalf("result = %+v", res)
	}
	got := map[string]report.Artifact{}
	for _, a := range res.Artifacts {
		got[strings.Join(a.Nested, "!")] = a
	}
	want := map[string]struct {
		name, version, sha1 string
	}{
		"":                       {"app", "1.0.0", ""},
		"BOOT-INF/lib/a-1.0.jar": {"a", "1.0", sha1hex(stored)},
		"BOOT-INF/lib/a-1.0.jar!lib/deep-0.1.jar": {"deep", "0.1", sha1hex(inner)},
		"WEB-INF/lib/b-2.0.jar":                   {"b", "2.0", sha1hex(deflated)},
	}
	if len(got) != len(want) {
		t.Fatalf("artifacts = %+v", res.Artifacts)
	}
	for k, w := range want {
		a, ok := got[k]
		if !ok || a.Name != w.name || a.Version != w.version || a.SHA1 != w.sha1 {
			t.Errorf("%q: got %+v, want %+v", k, a, w)
		}
	}
}

func TestJarShaded(t *testing.T) {
	b := buildZip(t,
		pomEntry("com.google.guava", "guava", "31.1-jre"),
		pomEntry("com.example", "tool", "2.1"),
		pomEntry("org.slf4j", "slf4j-api", "1.7.36"),
	)
	res := scanBytes(b, "tool-2.1.jar", defaultArchiveLimits)
	if len(res.Artifacts) != 3 {
		t.Fatalf("artifacts = %+v", res.Artifacts)
	}
	if a := res.Artifacts[0]; a.Name != "tool" || a.Version != "2.1" || a.Nested != nil {
		t.Fatalf("outer = %+v", a)
	}
	var embedded []string
	for _, a := range res.Artifacts[1:] {
		if len(a.Nested) != 1 || !isPomProperties(a.Nested[0]) {
			t.Errorf("embedded nested = %v", a.Nested)
		}
		embedded = append(embedded, a.GroupID+":"+a.ArtifactID+":"+a.Version)
	}
	slices.Sort(embedded)
	if !slices.Equal(embedded, []string{"com.google.guava:guava:31.1-jre", "org.slf4j:slf4j-api:1.7.36"}) {
		t.Fatalf("embedded = %v", embedded)
	}

	// Without a coordinate named like the file, every coordinate is
	// embedded and the outer one comes from the manifest or the name.
	res = scanBytes(b, "bundle-9.jar", defaultArchiveLimits)
	if a := res.Artifacts[0]; a.Name != "bundle" || a.Version != "9" || len(res.Artifacts) != 4 {
		t.Fatalf("artifacts = %+v", res.Artifacts)
	}
}

// nest wraps an archive n times.
func nest(t *testing.T, inner []byte, n int) []byte {
	for i := range n {
		inner = buildZip(t, zent{name: fmt.Sprintf("lib/level%d-1.0.jar", n-i), data: inner})
	}
	return inner
}

func TestJarLimits(t *testing.T) {
	zeros := bytes.Repeat([]byte{0}, 8<<20)
	many := make([]zent, 30)
	for i := range many {
		many[i] = zent{name: fmt.Sprintf("c/%d.class", i), data: []byte{1}}
	}
	small := defaultArchiveLimits
	small.MaxEntries = 20
	small.MaxTotalBytes = 1 << 20
	small.MaxNestedSize = 64 << 10

	cases := []struct {
		name  string
		data  []byte
		lim   archiveLimits
		limit string
	}{
		{"depth", nest(t, buildZip(t, pomEntry("g", "core", "1")), 6), defaultArchiveLimits, limitDepth},
		{"entries", buildZip(t, many...), small, limitEntries},
		{"ratio", buildZip(t, zent{name: "lib/bomb-1.0.jar", data: zeros}), defaultArchiveLimits, limitRatio},
		{"total", buildZip(t, zent{name: "lib/big-1.0.jar", data: randomBytes(2 << 20), stored: true}), small, limitSize},
		{"nested-in-memory", buildZip(t, zent{name: "lib/big-1.0.jar", data: randomBytes(128 << 10)}), small, limitSize},
		{"meta", buildZip(t, zent{name: "META-INF/MANIFEST.MF", data: randomBytes(2 << 20)}), small, limitSize},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res := scanBytes(tc.data, "outer-1.0.jar", tc.lim)
			if !slices.Contains(res.Limits, tc.limit) {
				t.Fatalf("limits = %v, want %q", res.Limits, tc.limit)
			}
			if len(res.Artifacts) == 0 || res.Artifacts[0].Name != "outer" {
				t.Fatalf("artifacts = %+v", res.Artifacts)
			}
		})
	}
}

func randomBytes(n int) []byte {
	b := make([]byte, n)
	x := uint32(2463534242)
	for i := range b {
		x ^= x << 13
		x ^= x >> 17
		x ^= x << 5
		b[i] = byte(x)
	}
	return b
}

func TestJarCorrupt(t *testing.T) {
	res := scanBytes([]byte("PK\x03\x04 this is not a zip"), "broken-2.0.jar", defaultArchiveLimits)
	if res.Corrupt != 1 || len(res.Artifacts) != 1 || res.Artifacts[0].Name != "broken" || res.Artifacts[0].Version != "2.0" {
		t.Fatalf("result = %+v", res)
	}
	// A nested archive that is not a zip.
	b := buildZip(t, pomEntry("g", "outer", "1"), zent{name: "lib/bad-1.0.jar", data: []byte("garbage")})
	res = scanBytes(b, "outer-1.jar", defaultArchiveLimits)
	if res.Corrupt != 1 || len(res.Artifacts) != 2 || res.Artifacts[1].Name != "bad" || res.Artifacts[1].SHA1 != sha1hex([]byte("garbage")) {
		t.Fatalf("result = %+v", res)
	}
}

func TestCollectJars(t *testing.T) {
	root := t.TempDir()
	jar := buildZip(t, pomEntry("org.example", "foo", "1.2.3"), zent{name: "lib/bar-1.0.jar", data: buildZip(t, pomEntry("org.example", "bar", "1.0"))})
	p := filepath.Join(root, "opt", "app", "foo-1.2.3.jar")
	os.MkdirAll(filepath.Dir(p), 0o755)
	if err := os.WriteFile(p, jar, 0o644); err != nil {
		t.Fatal(err)
	}
	os.WriteFile(filepath.Join(root, "opt", "app", "broken.war"), []byte("nope"), 0o644)
	env := testEnv(root)
	env.Proc = t.TempDir() // the descriptor below does not exist
	in := Inputs{
		OpenFiles: map[string][]OpenRef{"/opt/app/foo-1.2.3.jar": {{PID: 42, FD: 3}}},
		Owner: func(p string) (string, bool) {
			return "app-pkg", p == "/opt/app/foo-1.2.3.jar"
		},
	}
	sec := testCollector(env, in, "/").run(context.Background())
	if sec.Coverage != report.CoveragePartial || !strings.Contains(sec.Reason, "1 archive could not be parsed") {
		t.Fatalf("coverage %s %q", sec.Coverage, sec.Reason)
	}
	if len(sec.Artifacts) != 3 {
		t.Fatalf("artifacts = %+v", sec.Artifacts)
	}
	outer, nested := sec.Artifacts[1], sec.Artifacts[2]
	if outer.Path != "/opt/app/foo-1.2.3.jar" || outer.Nested != nil || outer.SHA1 != sha1hex(jar) || outer.SHA256 == "" ||
		outer.Size != int64(len(jar)) || !outer.InUse || outer.OwnerPackage != "app-pkg" {
		t.Fatalf("outer = %+v", outer)
	}
	if nested.Path != outer.Path || nested.Name != "bar" || !nested.InUse || nested.SHA256 != "" || nested.SHA1 == "" {
		t.Fatalf("nested = %+v", nested)
	}
	if sec.Digest == "" {
		t.Fatal("no digest")
	}

	// Same input, same cache: same digest, and the cache answers.
	again := testCollector(env, in, "/").run(context.Background())
	if again.Digest != sec.Digest {
		t.Fatalf("digest changed: %s %s", sec.Digest, again.Digest)
	}
}

func FuzzScanJar(f *testing.F) {
	f.Add(buildZip(f, pomEntry("g", "a", "1")))
	f.Add(buildZip(f, manifestEntry("Implementation-Version: 1"), zent{name: "lib/x.jar", data: buildZip(f, pomEntry("g", "x", "2")), stored: true}))
	f.Add([]byte("PK\x05\x06"))
	lim := defaultArchiveLimits
	lim.MaxTotalBytes = 4 << 20
	f.Fuzz(func(t *testing.T, b []byte) {
		res := scanBytes(b, "fuzz-1.0.jar", lim)
		if len(res.Artifacts) == 0 {
			t.Fatal("no artifact for the outer file")
		}
	})
}

// TestCollectOpenJar finds a jar held open by a process outside the walk
// paths, also after it was deleted, through the descriptor.
func TestCollectOpenJar(t *testing.T) {
	dir := t.TempDir()
	p := filepath.Join(dir, "Downloads", "tool-1.0.jar")
	os.MkdirAll(filepath.Dir(p), 0o755)
	jar := buildZip(t, pomEntry("org.example", "tool", "1.0"))
	if err := os.WriteFile(p, jar, 0o644); err != nil {
		t.Fatal(err)
	}
	f, err := os.Open(p)
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	in := Inputs{OpenFiles: map[string][]OpenRef{p: {{PID: os.Getpid(), FD: int(f.Fd())}}}}
	check := func(name string, sec *report.ArtifactsSection) {
		t.Helper()
		if len(sec.Artifacts) != 1 {
			t.Fatalf("%s: artifacts = %+v", name, sec.Artifacts)
		}
		a := sec.Artifacts[0]
		if a.Path != p || a.Name != "tool" || a.Version != "1.0" || !a.InUse || a.SHA1 != sha1hex(jar) {
			t.Fatalf("%s: artifact = %+v", name, a)
		}
	}
	check("open", newCollector(testEnv("/"), in).run(context.Background()))
	// Walked and open: reported once.
	check("walked", testCollector(testEnv("/"), in, dir).run(context.Background()))
	if err := os.Remove(p); err != nil {
		t.Fatal(err)
	}
	check("deleted", newCollector(testEnv("/"), in).run(context.Background()))
}
