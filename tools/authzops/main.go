// Command authzops writes the operation id constants of package
// server/authz from api/openapi/admin.yaml.
//
//	go run ./tools/authzops -spec api/openapi/admin.yaml -out server/authz/operations.go
//
// It reads the operation objects line by line (path items at two spaces,
// methods at four, operation fields at six) instead of parsing YAML, which
// is enough for the layout of admin.yaml. server/authz tests that the result
// matches the generated server interface.
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

var (
	methodLine   = regexp.MustCompile(`^    (get|put|post|delete|patch|head|options):\s*$`)
	operationID  = regexp.MustCompile(`^      operationId:\s*(\S+)\s*$`)
	publicMarker = regexp.MustCompile(`^      security:\s*\[\]\s*$`)
	pathLine     = regexp.MustCompile(`^  /\S*:\s*$`)
)

type op struct {
	id, method, path string
	public           bool
}

func main() {
	spec := flag.String("spec", "api/openapi/admin.yaml", "OpenAPI document")
	out := flag.String("out", "server/authz/operations.go", "output file")
	flag.Parse()
	if err := run(*spec, *out); err != nil {
		fmt.Fprintln(os.Stderr, "authzops:", err)
		os.Exit(1)
	}
}

func run(spec, out string) error {
	f, err := os.Open(spec)
	if err != nil {
		return err
	}
	defer f.Close()
	var (
		ops      []op
		cur      *op
		path     string
		inPaths  bool
		sc       = bufio.NewScanner(f)
		finished = func() {
			if cur != nil && cur.id != "" {
				ops = append(ops, *cur)
			}
			cur = nil
		}
	)
	for sc.Scan() {
		line := sc.Text()
		switch {
		case line == "paths:":
			inPaths = true
			continue
		case inPaths && line != "" && !strings.HasPrefix(line, " ") && !strings.HasPrefix(line, "#"):
			finished()
			inPaths = false
		}
		if !inPaths {
			continue
		}
		if pathLine.MatchString(line) {
			finished()
			path = strings.TrimSuffix(strings.TrimSpace(line), ":")
			continue
		}
		if m := methodLine.FindStringSubmatch(line); m != nil {
			finished()
			cur = &op{method: strings.ToUpper(m[1]), path: path}
			continue
		}
		if cur == nil {
			continue
		}
		if m := operationID.FindStringSubmatch(line); m != nil {
			cur.id = m[1]
		} else if publicMarker.MatchString(line) {
			cur.public = true
		}
	}
	if err := sc.Err(); err != nil {
		return err
	}
	finished()
	if len(ops) == 0 {
		return fmt.Errorf("%s: no operations found", spec)
	}
	sort.Slice(ops, func(i, j int) bool { return ops[i].id < ops[j].id })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/authzops from %s. DO NOT EDIT.\n\npackage authz\n\n", spec)
	b.WriteString("// Operation ids of the admin API, as passed in Request.Operation.\nconst (\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\t// Op%s is %s %s.\n\tOp%s = %q\n", exported(o.id), o.method, o.path, exported(o.id), exported(o.id))
	}
	b.WriteString(")\n\n// publicOps need no principal.\nvar publicOps = map[string]bool{\n")
	for _, o := range ops {
		if o.public {
			fmt.Fprintf(&b, "\tOp%s: true,\n", exported(o.id))
		}
	}
	b.WriteString("}\n\n// operations lists every operation id.\nvar operations = []string{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "\tOp%s,\n", exported(o.id))
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}

// exported is the operation id as oapi-codegen names the strict method.
func exported(id string) string {
	r := []rune(id)
	r[0] = unicode.ToUpper(r[0])
	return string(r)
}
