// Command dtoenums writes the enum values of the agent protocol DTOs for
// package agentproto/conformance, which needs valid values to build
// samples that channel adapters can convert.
//
//	go run ./tools/dtoenums -in agentproto/dto/dto.gen.go -out agentproto/conformance/enums.gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"sort"
	"strconv"
)

func main() {
	in := flag.String("in", "agentproto/dto/dto.gen.go", "generated DTO file")
	out := flag.String("out", "agentproto/conformance/enums.gen.go", "output file")
	pkg := flag.String("dto", "github.com/bomcensus/bomcensus/agentproto/dto", "import path of the DTO package")
	flag.Parse()
	if err := run(*in, *out, *pkg); err != nil {
		fmt.Fprintln(os.Stderr, "dtoenums:", err)
		os.Exit(1)
	}
}

func run(in, out, pkg string) error {
	f, err := parser.ParseFile(token.NewFileSet(), in, nil, 0)
	if err != nil {
		return err
	}
	enums := map[string][]string{}
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		for _, s := range gd.Specs {
			vs := s.(*ast.ValueSpec)
			id, ok := vs.Type.(*ast.Ident)
			if !ok || len(vs.Values) != 1 {
				continue
			}
			lit, ok := vs.Values[0].(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				continue
			}
			v, err := strconv.Unquote(lit.Value)
			if err != nil {
				return err
			}
			enums[id.Name] = append(enums[id.Name], v)
		}
	}
	names := make([]string, 0, len(enums))
	for n := range enums {
		names = append(names, n)
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/dtoenums from %s. DO NOT EDIT.\n\npackage conformance\n\n", in)
	fmt.Fprintf(&b, "import (\n\t\"reflect\"\n\n\t%q\n)\n\n", pkg)
	b.WriteString("// enums are the values of the string enum types of package dto.\nvar enums = map[reflect.Type][]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\treflect.TypeFor[dto.%s](): {", n)
		for i, v := range enums[n] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", v)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o644)
}
